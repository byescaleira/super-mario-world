#!/usr/bin/env python3
"""Emits Core/include/smw_symbols.h from the asar WLA symbol file.

The runtime's game-aware features (widescreen, haptics, ...) address RAM by
the names given in SMWDisX's rammap.asm, never by hard-coded numbers.
Usage: gen_symbols.py <smw.sym> <out.h>
"""
import sys

LABELS = [
    "GameMode", "Layer1XPos", "Layer1YPos", "Layer2XPos", "Layer2YPos",
    "LastScreenHoriz", "LevelScrLength", "ScreenMode", "LevelModeSetting",
    "IRQNMICommand", "SPCIO0", "SPCIO1", "SPCIO2", "SPCIO3",
    # progress, for Game Center achievements and leaderboards
    "ExitsCompleted", "SwitchBlockFlags", "CutsceneID", "DragonCoinsCollected",
    "PlayerScore", "IsTwoPlayerGame",
    # optional infinite lives
    "PlayerLives", "SavedPlayerLives",
]
CONSTANTS = {"StatusBarHeight": 36}

syms = {}
for line in open(sys.argv[1]):
    line = line.strip()
    if not line or line.startswith(";") or line.startswith("["):
        continue
    addr, _, name = line.partition(" ")
    if ":" not in addr:
        continue
    bank, off = addr.split(":")
    syms.setdefault(name, (int(bank, 16) << 16) | int(off, 16))

out = ["// Generated by scripts/gen_symbols.py from the SMWDisX symbol file. Do not edit.",
       "#ifndef SMW_SYMBOLS_H", "#define SMW_SYMBOLS_H", ""]
for name in LABELS:
    if name not in syms:
        sys.exit(f"missing symbol {name}")
    out.append(f"#define SYM_{name} 0x{syms[name]:06X}")
out.append("")
for name, value in CONSTANTS.items():
    out.append(f"#define SMW_{name} {value}")
out += ["", "#endif", ""]
open(sys.argv[2], "w").write("\n".join(out))
